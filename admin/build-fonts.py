"""Optional maintenance command; ordinary site builds use the committed WOFF2 files.

Requires fonttools[woff]. Keep original fonts as the fallback for uncommon glyphs.
"""
from pathlib import Path
from html.parser import HTMLParser
from hashlib import sha256
from io import BytesIO
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent

class VisibleText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ignored = 0
        self.characters = set()
    def handle_starttag(self, tag, attrs):
        if tag in ('script', 'style'): self.ignored += 1
    def handle_endtag(self, tag):
        if tag in ('script', 'style'): self.ignored -= 1
    def handle_data(self, text):
        if not self.ignored: self.characters.update(map(ord, text))

# All ASCII, Italian accents, ordinary punctuation, plus the current site's text.
# The original faces remain available for every character outside this range.
characters = set(range(32, 127)) | set(map(ord, 'ÀÈÉÌÒÙàèéìòù©®°·€£’‘“”–—…'))
for file in ROOT.rglob('*.html'):
    if any(part.startswith('.') or part in ('admin', 'node_modules') for part in file.relative_to(ROOT).parts): continue
    parser = VisibleText()
    parser.feed(file.read_text(encoding='utf-8'))
    characters.update(parser.characters)

fonts = [('Be Vietnam Pro', 'normal', str(weight),
          f'assets/{"site" if weight == 300 else "shop"}-fonts/be-vietnam-pro-{weight}-latin.woff2',
          f'giuggioloni-sans-{weight}') for weight in (300, 400, 500, 600, 700)]
fonts += [('Playfair Display', 'normal', weight, 'assets/shop-fonts/playfair-display-700-latin.woff2', 'giuggioloni-serif') for weight in ('400', '600', '700')]
fonts += [('Playfair Display', 'italic', '400', 'assets/site-fonts/playfair-display-400-italic-latin.woff2', 'giuggioloni-serif-italic')]
rules, generated = [], {}
for family, style, weight, source, stem in fonts:
    if source not in generated:
        font = TTFont(ROOT / source, recalcTimestamp=False)
        supported = characters & set(font.getBestCmap())
        options = subset.Options()
        options.layout_features = ['*']  # Keep kerning, ligatures and numerical variants.
        options.recalc_timestamp = False
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=supported)
        sub.subset(font)
        # A distinct internal name for these subsets; CSS aliases keep the site styles.
        family_name = 'Giuggioloni Serif Core' if family == 'Playfair Display' else 'Giuggioloni Sans Core'
        names = {1: family_name, 2: style.title() if style != 'normal' else 'Regular',
                 3: stem, 4: family_name + ' ' + weight, 6: stem, 16: family_name}
        for record in font['name'].names:
            if record.nameID in names:
                record.string = names[record.nameID].encode(record.getEncoding())
        buffer = BytesIO()
        font.save(buffer)
        body = buffer.getvalue()
        filename = stem + '-' + sha256(body).hexdigest()[:12] + '.woff2'
        (ROOT / 'assets/site-fonts' / filename).write_bytes(body)
        # Be explicit: a future character outside this subset uses the original face.
        unicode_range = ','.join('U+' + format(code, 'X') for code in sorted(supported))
        generated[source] = (filename, unicode_range)
        print(source, (ROOT / source).stat().st_size, '->', len(body))
    filename, unicode_range = generated[source]
    rules.append(f'@font-face{{font-family:"{family}";font-style:{style};font-weight:{weight};font-display:swap;src:url(site-fonts/{filename}) format("woff2");unicode-range:{unicode_range}}}')
(ROOT / 'admin/site-fonts.css').write_text('/* Generated by admin/build-fonts.py; appended after the original font faces. */\n' + '\n'.join(rules) + '\n', encoding='utf-8')
